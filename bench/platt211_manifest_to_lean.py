#!/usr/bin/env python3
"""Generate the literal Lean data for the completed Platt (2.11) chain.

The JSON manifest remains the human/runtime receipt.  This generator copies
only integer fields needed by the formal gap/carry composition; timings and
tool metadata stay in the benchmark files.
"""

from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "bench/results/manifests/platt211_1e12.json"
TARGET = ROOT / "LeanCompCert/Ports/ArraySegMobiusPlatt211ManifestData.lean"


def main() -> None:
    raw = SOURCE.read_bytes()
    document = json.loads(raw)
    rows = document["windows"]
    if len(rows) != 1092:
        raise ValueError(f"expected 1092 windows, got {len(rows)}")

    largest_root = math.isqrt(max(row["hi"] for row in rows))
    prime_mask = bytearray(b"\x01") * (largest_root + 1)
    prime_mask[:2] = b"\x00\x00"
    for p in range(2, math.isqrt(largest_root) + 1):
        if prime_mask[p]:
            prime_mask[p * p:largest_root + 1:p] = b"\x00" * (
                (largest_root - p * p) // p + 1
            )
    primes = [p for p in range(2, largest_root + 1) if prime_mask[p]]

    out = [
        "-- This file is generated by bench/platt211_manifest_to_lean.py.",
        f"-- Source SHA-256: {hashlib.sha256(raw).hexdigest()}",
        "-- Copyright (c) 2026 Gershon Bialer. All rights reserved.",
        "-- Released under Apache 2.0; see LICENSE.",
        "",
        "namespace LeanCompCert.Ports.ArraySegMobiusPlatt211ManifestData",
        "",
        "set_option maxRecDepth 200000",
        "",
        "/-- One retained CompCert window and the three extrema carry cells.",
        "The observations and window shape are copied verbatim from the pinned",
        "production manifest.  The compact `Cfg.ofRange` fields and the formal",
        "paper-side `strictThreshold` are deterministically recomputed. -/",
        "structure Row where",
        "  idx : Nat",
        "  lo : Nat",
        "  hi : Nat",
        "  segLen : Nat",
        "  segCount : Nat",
        "  rootCount : Nat",
        "  bootBound : Nat",
        "  mainCount : Nat",
        "  rootCap : Nat",
        "  markSteps : Nat",
        "  threshold : Nat",
        "  strictThreshold : Nat",
        "  seed : Nat",
        "  tOut : Nat",
        "  tMax : Nat",
        "  tMin : Nat",
        "  violations : Nat",
        "  deriving Repr, DecidableEq",
        "",
        "/-- The complete 1,092-window production chain through `10^12`. -/",
        "def rows : List Row := [",
    ]
    for index, row in enumerate(rows):
        slots = row["slots"]
        root_cap = math.isqrt(row["hi"])
        root_count = max(1, (root_cap + row["seglen"] - 1) // row["seglen"])
        root_len = root_count * row["seglen"]
        boot_bound = max(math.isqrt(root_len), 2)
        active_primes = [p for p in primes if p <= max(boot_bound, root_cap)]
        main_count = len(active_primes)
        mark_steps = sum(row["seglen"] // p + 2 for p in active_primes) + 16
        budget = (row["hi"] + 1) // 2
        strict_threshold = math.isqrt((1 << 125) // (row["hi"] + 1)) - budget
        if strict_threshold < 0:
            strict_threshold = 0
        comma = "," if index + 1 < len(rows) else ""
        out.append(
            "  { idx := %d, lo := %d, hi := %d, segLen := %d, "
            "segCount := %d, rootCount := %d, bootBound := %d, "
            "mainCount := %d, rootCap := %d, markSteps := %d, "
            "threshold := %d, strictThreshold := %d, seed := %d, "
            "tOut := %d, tMax := %d, tMin := %d, violations := %d }%s"
            % (
                row["idx"], row["lo"], row["hi"], row["seglen"],
                row["segcount"], root_count, boot_bound, main_count, root_cap,
                mark_steps, row["thr"], strict_threshold, row["seed"],
                slots[0], slots[1], slots[2], row["viol"], comma,
            )
        )
    out.extend([
        "]",
        "",
        "end LeanCompCert.Ports.ArraySegMobiusPlatt211ManifestData",
        "",
    ])
    TARGET.write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
