def compcert_flags(compcert_dir):
    """-R/-Q flags for the compiled CompCert tree, from its _CoqProject."""
    mappings, proj = [], os.path.join(compcert_dir, "_CoqProject")
    if os.path.exists(proj):
        toks = open(proj).read().split()
        i = 0
        while i < len(toks):
            if toks[i] in ("-R", "-Q") and i + 2 < len(toks):
                mappings.append((toks[i], toks[i + 1], toks[i + 2]))
                i += 3
            else:
                i += 1
    else:
        mappings = [("-R", d, l) for d, l in DEFAULT_MAPPINGS]
    flags = []
    for opt, subdir, logical in mappings:
        physical = os.path.join(compcert_dir, subdir)
        if os.path.isdir(physical):
            flags += [opt, physical, logical]
    if not flags:
        raise GenError(f"no CompCert subdirectories found under {compcert_dir}")
    return flags


def find_coqc(explicit, flags, outdir):
    """Probe candidate coqc binaries: the first that can Require CompCert's
    compiled Clight wins (this catches .vo version mismatches empirically)."""
    if explicit:
        candidates = [explicit]
    else:
        candidates = []
        if os.environ.get("COQC"):
            candidates.append(os.environ["COQC"])
        candidates.append("coqc")
        candidates += sorted(glob.glob(os.path.expanduser("~/.opam/*/bin/coqc")))
    probe = os.path.join(outdir, "probe.v")
    with open(probe, "w") as fh:
        fh.write("From compcert Require Import Clight.\n")
    tried = []
    for cand in candidates:
        if shutil.which(cand) is None and not os.access(cand, os.X_OK):
            tried.append(f"{cand}: not found")
            continue
        r = subprocess.run([cand] + flags + [probe],
                           capture_output=True, text=True)
        if r.returncode == 0:
            ver_lines = subprocess.run(
                [cand, "--version"], capture_output=True, text=True
            ).stdout.splitlines()
            return cand, ver_lines[0] if ver_lines else "unknown version"
        tried.append(f"{cand}: {r.stderr.strip().splitlines()[-1] if r.stderr.strip() else 'failed'}")
    raise GenError("no working coqc found (needs the Coq version the CompCert "
                   ".vo files were built with).  Tried:\n  " + "\n  ".join(tried))


# --------------------------------------------------------------------------
# Expected-list generation (C events -> Coq terms)
# --------------------------------------------------------------------------

IDENT_DEF_RE = re.compile(r'^Definition\s+(_[A-Za-z0-9_\']*)\s*:\s*ident\s*:=\s*'
                          r'\$"([^"]*)"\s*\.', re.M)
FUNC_DEF_RE = re.compile(r'^Definition\s+f_(l_\w+)\s*:=\s*\{\|', re.M)


def ident_map_of_v(v_text):
    """Map C-level name -> Coq ident constant, read from the certificate .v's
    `Definition _x : ident := $"x".` lines (the same constants clightgen uses
    inside fn_body, so referencing them by name is exact)."""
    return {cname: coqname for coqname, cname in IDENT_DEF_RE.findall(v_text)}


class ExpectedPrinter:
    def __init__(self, ident_map, func):
        self.ident_map = ident_map
        self.func = func

    def ident(self, cname):
        try:
            return self.ident_map[cname]
        except KeyError:
            raise GenError(
                f"{self.func}: C name {cname!r} has no `Definition _{cname} : "
                f"ident := $\"{cname}\".` in the certificate .v")

    def dsc(self, d):
        kind = d[0]
        if kind == "var":
            return f"(Dvar {self.ident(d[1])})"
        if kind == "lit":
            _, value, width = d
            return f"(Dlit {width} {value})"
        if kind == "bin":
            return f"(Dbin {d[1]} {self.dsc(d[2])} {self.dsc(d[3])})"
        if kind == "un":
            return f"(Dun {d[1]} {self.dsc(d[2])})"
        if kind == "call":
            raise GenError(f"{self.func}: call expression {d[1]}(...) in an "
                           "assignment is not representable in Clight events")
        raise GenError(f"{self.func}: unknown C descriptor {d!r}")

    def event(self, e):
        kind = e[0]
        if kind == "assign":
            return f"EAssign {self.ident(e[1])} {self.dsc(e[2])}"
        if kind == "loop":
            return f"ELoop (Some {self.dsc(e[1])})"
        if kind == "endloop":
            return "EEndLoop"
        if kind == "if":
            return f"EIf {self.dsc(e[1])}"
        if kind == "else":
            return "EElse"
        if kind == "endif":
            return "EEndIf"
        if kind == "label":
            return f"ELabel {self.ident(e[1])}"
        if kind == "goto":
            return f"EGoto {self.ident(e[1])}"
        if kind == "return":
            return "EReturn None" if e[1] is None \
                else f"EReturn (Some {self.dsc(e[1])})"
        if kind == "call":
            _, name, dest, args = e
            dst = "None" if dest is None else f"(Some {self.ident(dest)})"
            arg_list = "[" + "; ".join(self.dsc(a) for a in args) + "]"
            return f"ECall {dst} {self.ident(name)} {arg_list}"
        raise GenError(f"{self.func}: unknown C event {e!r}")


def check_file_text(c_funcs, ident_map):
    out = ["(* Expected structural event lists (computed from the certificate",
           "   C file) and kernel-checked correspondence lemmas.",
           "   Generated by scripts/clight-correspond-coq.py -- do not edit. *)",
           "From Coq Require Import String List ZArith.",
           "From compcert Require Import Coqlib Integers AST Ctypes Cop "
           "Clight Clightdefs.",
           "From Correspond Require Import CorrespondPrelude Cert.",
           "Import ListNotations.",
           "Local Open Scope Z_scope.",
           ""]
    for name, cf in c_funcs.items():
        pr = ExpectedPrinter(ident_map, name)
        lines = [pr.event(e) for e in cf.events]
        out.append(f"Definition expected_{name} : list ev :=")
        out.append("  [" + ";\n   ".join(lines) + "].")
        out.append("")
        out.append(f"Lemma correspondence_{name} :")
        out.append(f"  events (fn_body f_{name}) = expected_{name}.")
        out.append(f"Proof. vm_cast_no_check (eq_refl expected_{name}). Qed.")
        out.append("")
    return "\n".join(out)


