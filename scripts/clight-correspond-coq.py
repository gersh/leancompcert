def run_coqc(coqc, flags, path, label):
    t0 = time.monotonic()
    r = subprocess.run([coqc] + flags + [path], capture_output=True, text=True)
    dt = time.monotonic() - t0
    return r, dt


def check_pair(cc_mod, c_path, v_path, outdir, coqc, flags, quiet_fail=False):
    """Generate + compile + prove.  Returns 0 on full success, 1 when the
    correspondence lemma itself is rejected by Coq (the discrimination case),
    and 2 on infrastructure failure (certificate or prelude did not compile).
    The self-test's negative control accepts only 1, so a broken environment
    cannot masquerade as a rejected mutant."""
    c_text = open(c_path).read()
    v_text = open(v_path).read()
    c_funcs = cc_mod.parse_c_functions(c_text)
    if not c_funcs:
        raise GenError(f"no l_* certificate function found in {c_path}")
    v_func_names = set(FUNC_DEF_RE.findall(v_text))
    missing = sorted(set(c_funcs) - v_func_names)
    if missing:
        raise GenError(f"{v_path} lacks Definition f_<name> for: {missing}")
    extra = sorted(v_func_names - set(c_funcs))
    if extra:
        raise GenError(f"{v_path} defines certificate functions absent from "
                       f"the C file (would go unchecked): {extra}")
    ident_map = ident_map_of_v(v_text)

    cert_v = os.path.join(outdir, "Cert.v")
    shutil.copyfile(v_path, cert_v)
    with open(os.path.join(outdir, "CorrespondPrelude.v"), "w") as fh:
        fh.write(PRELUDE)
    with open(os.path.join(outdir, "CorrespondCheck.v"), "w") as fh:
        fh.write(check_file_text(c_funcs, ident_map))

    local_flags = flags + ["-Q", outdir, "Correspond"]

    # Cert.v can be large; cache its .vo keyed on content + toolchain.
    stamp_path = os.path.join(outdir, "Cert.stamp")
    key = hashlib.sha256(("\0".join([v_text, coqc] + local_flags))
                         .encode()).hexdigest()
    cert_vo = os.path.join(outdir, "Cert.vo")
    if os.path.exists(cert_vo) and os.path.exists(stamp_path) \
            and open(stamp_path).read().strip() == key:
        print(f"  Cert.v: cached ({os.path.basename(v_path)} unchanged)")
    else:
        r, dt = run_coqc(coqc, local_flags, cert_v, "Cert.v")
        if r.returncode != 0:
            print(f"  FAIL: coqc could not compile the certificate .v "
                  f"({dt:.1f}s):\n{r.stderr}", file=sys.stderr)
            return 2
        print(f"  Cert.v: compiled in {dt:.1f}s "
              f"({os.path.getsize(cert_v)} bytes)")
        with open(stamp_path, "w") as fh:
            fh.write(key + "\n")

    r, dt = run_coqc(coqc, local_flags,
                     os.path.join(outdir, "CorrespondPrelude.v"), "prelude")
    if r.returncode != 0:
        print(f"  FAIL: prelude did not compile ({dt:.1f}s):\n{r.stderr}",
              file=sys.stderr)
        return 2
    print(f"  CorrespondPrelude.v: compiled in {dt:.1f}s")

    r, dt = run_coqc(coqc, local_flags,
                     os.path.join(outdir, "CorrespondCheck.v"), "check")
    if r.returncode != 0:
        if not quiet_fail:
            print(f"  FAIL: correspondence lemma rejected by Coq ({dt:.1f}s):"
                  f"\n{r.stderr}", file=sys.stderr)
        else:
            print(f"  correspondence lemma rejected by Coq ({dt:.1f}s) "
                  "[expected for negative control]")
        return 1
    for name, cf in c_funcs.items():
        ops = [e[2][1] for e in cf.events
               if e[0] == "assign" and e[2][0] == "bin"]
        print(f"  {name}: Qed -- {len(cf.events)} structural events "
              f"kernel-checked ({len(ops)} binary ops)")
    print(f"  CorrespondCheck.v: proved in {dt:.1f}s")
    return 0


def self_test(cc_mod, outdir, coqc, flags):
    """Positive + negative control on a generated mini certificate."""
    st_dir = os.path.join(outdir, "selftest")
    os.makedirs(st_dir, exist_ok=True)
    mini_c = os.path.join(st_dir, "mini.c")
    with open(mini_c, "w") as fh:
        fh.write(MINI_C)
    r = subprocess.run(["clightgen", "-normalize", mini_c],
                       capture_output=True, text=True, cwd=st_dir)
    if r.returncode != 0:
        raise GenError(f"clightgen failed on the self-test file:\n{r.stderr}")
    mini_v = os.path.join(st_dir, "mini.v")

    print("self-test positive control (mini certificate):")
    pos_dir = os.path.join(st_dir, "pos")
    os.makedirs(pos_dir, exist_ok=True)
    if check_pair(cc_mod, mini_c, mini_v, pos_dir, coqc, flags) != 0:
        print("SELF-TEST RESULT: FAIL (positive control did not prove)")
        return 1

    print("self-test negative control (Oadd mutated to Osub in the .v):")
    mut_v = os.path.join(st_dir, "mini-mutated.v")
    v_text = open(mini_v).read()
    if "Ebinop Oadd" not in v_text:
        raise GenError("self-test .v has no Ebinop Oadd to mutate")
    with open(mut_v, "w") as fh:
        fh.write(v_text.replace("Ebinop Oadd", "Ebinop Osub", 1))
    neg_dir = os.path.join(st_dir, "neg")
    os.makedirs(neg_dir, exist_ok=True)
    rc = check_pair(cc_mod, mini_c, mut_v, neg_dir, coqc, flags,
                    quiet_fail=True)
    if rc == 0:
        print("SELF-TEST RESULT: FAIL (mutated .v was wrongly accepted)")
        return 1
    if rc != 1:
        print("SELF-TEST RESULT: FAIL (negative control hit an "
              "infrastructure failure, not a lemma rejection)")
        return 1
    print("SELF-TEST RESULT: PASS (genuine pair proved; mutant rejected)")
    return 0


def main(argv):
    ap = argparse.ArgumentParser(
        description="Kernel-checked structural correspondence between a "
                    "certificate C file and its clightgen .v output.")
    ap.add_argument("cert_c", nargs="?", help="certificate C file")
    ap.add_argument("cert_v", nargs="?", help="clightgen output .v file")
    ap.add_argument("outdir", nargs="?", help="working/output directory")
    ap.add_argument("--compcert", default=DEFAULT_COMPCERT,
                    help="compiled CompCert Coq development "
                         f"(default: {DEFAULT_COMPCERT})")
    ap.add_argument("--coqc", default=None,
                    help="coqc binary (default: probe $COQC, PATH, opam "
                         "switches for one matching the .vo version)")
    ap.add_argument("--self-test", action="store_true",
                    help="run positive+negative controls on a generated mini "
                         "certificate (only <outdir> is required)")
    args = ap.parse_args(argv[1:])

    if args.self_test:
        if args.outdir is None:
            args.outdir = args.cert_c   # allow `--self-test OUTDIR` form
        if args.outdir is None or args.cert_v is not None:
            ap.error("--self-test takes exactly one directory argument")
    elif not (args.cert_c and args.cert_v and args.outdir):
        ap.error("cert_c, cert_v and outdir are required (or use --self-test)")

    outdir = os.path.abspath(args.outdir)
    os.makedirs(outdir, exist_ok=True)
    cc_mod = load_c_parser()
    try:
        flags = compcert_flags(os.path.abspath(args.compcert))
        coqc, ver = find_coqc(args.coqc, flags, outdir)
        print(f"coqc: {coqc} ({ver})")
        if args.self_test:
            return self_test(cc_mod, outdir, coqc, flags)
        print(f"checking {args.cert_c} against {args.cert_v}:")
        rc = check_pair(cc_mod, args.cert_c, os.path.abspath(args.cert_v),
                        outdir, coqc, flags)
        print("RESULT:", "PASS (Coq kernel accepted the correspondence)"
              if rc == 0 else "FAIL")
        return rc
    except (OSError, GenError, cc_mod.ParseError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
