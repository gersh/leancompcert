#!/usr/bin/env python3
"""Coq-mechanized structural correspondence: certificate C vs clightgen .v.

Usage:
  clight-correspond-coq.py [options] <cert.c> <cert.v> <outdir>
  clight-correspond-coq.py [options] --self-test <outdir>

This is the proof-level upgrade of scripts/clight-correspond.py (roadmap M6:
"proof-level correspondence in Coq/Lean rather than a checker").  The Python
checker parses BOTH sides itself and compares event streams in Python; here
only the C side is parsed by Python (reusing clight-correspond.py's C parser).
The Clight side is never re-parsed: the clightgen-produced .v file is compiled
by coqc against the real CompCert 3.17 Coq development, a generated Coq
`events` function (over CompCert's own `Clight.statement` AST) extracts the
structural event stream from `fn_body f_l_*`, and Coq's kernel checks

    Lemma correspondence_<f> : events (fn_body f_<f>) = expected_<f>.
    Proof. vm_cast_no_check (eq_refl expected_<f>). Qed.

where `expected_<f>` is the event list this script computes from the C file.
A Qed means CompCert's kernel-checked term -- the exact term CompCert's
correctness proof starts from -- has precisely the expected assignment/
operator/operand/control-flow stream.  The trusted base for the *comparison*
shrinks from a Python s-expression parser of .v text to: this script's C-side
parser + expected-list printer, the small generated Coq prelude below, and Coq
itself.

Generated files in <outdir>:
  Cert.v               verbatim copy of the certificate .v (module Cert)
  CorrespondPrelude.v  event type + `events : statement -> list ev`
  CorrespondCheck.v    expected event lists + correspondence lemmas
  probe.v/.vo, *.vo, Cert.stamp   build artifacts / cache

Exit status: 0 iff every lemma Qeds (and, under --self-test, iff the mutated
negative control FAILS to Qed).

HONESTY NOTE: like the Python checker this is *structural* translation
validation, not a semantics proof: casts are erased on both sides, evaluation
order/overflow/memory are not modeled, and the C-side event extraction is
still Python.  What is new is that the .v side is no longer parsed by a
regex/s-expression walker: Coq elaborates the certificate term itself and the
kernel validates the equality.

LIMITATIONS:
  * C-side parsing limitations are inherited from clight-correspond.py
    (emitter-shaped C only; see its docstring).
  * A C `while` is matched against the exact `Clight.Swhile` unfolding
    (Sloop (Ssequence (Sifthenelse c Sskip Sbreak) body) Sskip), which is what
    clightgen -normalize emits; a rolled `Sloop` of any other shape extracts
    as `ELoop None` and will NOT match a C while (stricter than the Python
    checker, which let a bare Sloop match any condition).
  * Calls are compared as full `ECall` events -- result destination, callee
    ident, and every argument descriptor in order (`v = f(a);` maps to
    Clight's `Scall (Some _v) (Evar _f _) [a]`).  Calls nested inside larger
    expressions are rejected: Clight has no call expression and the emitter's
    certificate fragment never produces them.
  * `Econst_float`/`Econst_single` and address-of/deref/field expressions
    extract as `Dunknown`, and `Sassign`/`Sbuiltin`/`Sswitch` as `EOther`:
    the expected list never contains these, so any occurrence FAILS the
    proof (conservative, mirrors the Python checker's parse errors).
"""

