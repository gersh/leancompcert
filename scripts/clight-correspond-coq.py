PRELUDE = '''\
(* Structural correspondence event extraction over CompCert Clight statements.
   Generated by scripts/clight-correspond-coq.py -- do not edit. *)
From Coq Require Import String List ZArith.
From compcert Require Import Coqlib Integers AST Ctypes Cop Clight Clightdefs.
Import ListNotations.

(* Normalized expression descriptor (casts erased; mirrors the descriptor
   space of scripts/clight-correspond.py). *)
Inductive dsc : Type :=
| Dvar (x : ident)
| Dlit (width : nat) (value : Z)
| Dbin (op : Cop.binary_operation) (l r : dsc)
| Dun (op : Cop.unary_operation) (a : dsc)
| Dunknown.

(* Ordered structural event. *)
Inductive ev : Type :=
| EAssign (dest : ident) (rhs : dsc)
| ELoop (cond : option dsc)
| EEndLoop
| EIf (cond : dsc)
| EElse
| EEndIf
| ELabel (l : ident)
| EGoto (l : ident)
| EReturn (r : option dsc)
| ECall (dst : option ident) (f : ident) (args : list dsc)
| EOther.

Fixpoint dsc_of_expr (e : Clight.expr) : dsc :=
  match e with
  | Ecast e' _ => dsc_of_expr e'          (* casts erased on both sides *)
  | Etempvar x _ => Dvar x
  | Evar x _ => Dvar x
  | Econst_int i _ => Dlit 32 (Int.unsigned i)
  | Econst_long i _ => Dlit 64 (Int64.unsigned i)
  | Ebinop op l r _ => Dbin op (dsc_of_expr l) (dsc_of_expr r)
  | Eunop op a _ => Dun op (dsc_of_expr a)
  | _ => Dunknown                          (* never expected: forces FAIL *)
  end.

(* Event stream of a Clight statement.  An [Sloop] in the exact shape of
   [Clight.Swhile]'s unfolding (what clightgen emits for a C [while])
   recovers the loop condition; any other [Sloop] yields [ELoop None]. *)
Fixpoint events (s : Clight.statement) : list ev :=
  match s with
  | Sskip | Sbreak | Scontinue => []
  | Sassign _ _ => [EOther]
  | Sset dst e => [EAssign dst (dsc_of_expr e)]
  | Scall dst (Evar f _) args => [ECall dst f (map dsc_of_expr args)]
  | Scall _ _ _ => [EOther]
  | Sbuiltin _ _ _ _ => [EOther]
  | Ssequence s1 s2 => events s1 ++ events s2
  | Sifthenelse c s1 s2 =>
      EIf (dsc_of_expr c) :: events s1 ++ EElse :: events s2 ++ [EEndIf]
  | Sloop (Ssequence (Sifthenelse c Sskip Sbreak) body) Sskip =>
      ELoop (Some (dsc_of_expr c)) :: events body ++ [EEndLoop]
  | Sloop s1 s2 => ELoop None :: events s1 ++ events s2 ++ [EEndLoop]
  | Sreturn None => [EReturn None]
  | Sreturn (Some e) => [EReturn (Some (dsc_of_expr e))]
  | Sswitch _ _ => [EOther]
  | Slabel l s1 => ELabel l :: events s1
  | Sgoto l => [EGoto l]
  end.
'''

MINI_C = '''\
#include <stdint.h>

uint64_t l_help(uint64_t x)
{
    return x + UINT64_C(1);
}

uint64_t l_mini(void)
{
    uint64_t v_0;
    uint64_t v_1;
    uint64_t v_2;
    v_0 = UINT64_C(2);
    v_1 = v_0 + UINT64_C(3);
    l_help(v_1);
    v_2 = v_1 * v_0;
    return v_2;
}
'''


class GenError(Exception):
    pass


def load_c_parser():
    """Import scripts/clight-correspond.py (hyphenated name) as a module."""
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "clight-correspond.py")
    spec = importlib.util.spec_from_file_location("clight_correspond", path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["clight_correspond"] = mod   # required for @dataclass
    spec.loader.exec_module(mod)
    return mod


